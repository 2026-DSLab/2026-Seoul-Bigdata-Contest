
##서울시 상권분석서비스(길단위인구-행정동) 전처리 코드
import pandas as pd

# 데이터 불러오기
df = pd.read_csv(
    "../../data/raw/서울시 상권분석서비스(길단위인구-행정동).csv",
    encoding="cp949"
)

# ---------------------------
# 1. 2504 분기만 남기기
# ---------------------------
# 기준_년분기_코드가 숫자/문자 혼재 가능하므로 문자열로 비교
df = df[df["기준_년분기_코드"].astype(str) == "20254"].copy()

# ---------------------------
# 2. 자치구 코드 생성
# ---------------------------
# 행정동 코드 앞 5자리 → 자치구 코드
df["자치구_코드"] = df["행정동_코드"].astype(str).str[:5].astype(int)

# ---------------------------
# 3. 자치구 이름 매핑
# ---------------------------
gu_map = {
    11110: "종로구", 11140: "중구", 11170: "용산구",
    11200: "성동구", 11215: "광진구", 11230: "동대문구",
    11260: "중랑구", 11290: "성북구", 11305: "강북구",
    11320: "도봉구", 11350: "노원구", 11380: "은평구",
    11410: "서대문구", 11440: "마포구", 11470: "양천구",
    11500: "강서구", 11530: "구로구", 11545: "금천구",
    11560: "영등포구", 11590: "동작구", 11620: "관악구",
    11650: "서초구", 11680: "강남구", 11710: "송파구",
    11740: "강동구"
}

df["자치구_코드_명"] = df["자치구_코드"].map(gu_map)

# 컬럼 위치 조정
gu_code = df.pop("자치구_코드")
gu_name = df.pop("자치구_코드_명")

df.insert(1, "자치구_코드", gu_code)
df.insert(2, "자치구_코드_명", gu_name)

# ---------------------------
# 결과 확인
# ---------------------------
print(df.head())

df.to_csv(
    "../../data/preprocessed/상권분석_길단위인구_행정동_20254분기.csv",
    index=False,
    encoding="utf-8-sig"
)