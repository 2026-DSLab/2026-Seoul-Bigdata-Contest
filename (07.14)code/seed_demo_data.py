def seed():
    inserted = 0
    for group in (_GROUP_HIP, _GROUP_LOCAL, _GROUP_MASS):
        for profile in group:
            lat, lng = _jitter(_CENTER_LAT, _CENTER_LNG)
            data = _build_fake_data(profile, lat, lng)
            mbti = compute_mbti(data)
            db.insert_store(
                상호명=data["상호명"], 구=data["구"], 동=data["동"],
                lat=lat, lng=lng, 업종_카테고리=data["업종_카테고리"],
                mbti_code=mbti["code"], mbti_axes=mbti["axes"],
                input_data=data, reports=None, is_seed=True,
            )
            inserted += 1
            print(f"  [seed] {data['상호명']:14s} MBTI={mbti['code']}  ({lat:.5f}, {lng:.5f})")

    print(f"\n 시드 완료: {inserted}곳 삽입 (db: {db.DB_PATH})")


if __name__ == "__main__":
    seed()
