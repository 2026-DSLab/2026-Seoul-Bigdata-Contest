def _jitter(lat: float, lng: float, radius_m: float = 120) -> tuple[float, float]:
    d_lat = random.uniform(-radius_m, radius_m) / 111_320
    d_lng = random.uniform(-radius_m, radius_m) / (111_320 * 0.79)  # 위도 37.5 근사 보정
    return round(lat + d_lat, 6), round(lng + d_lng, 6)


